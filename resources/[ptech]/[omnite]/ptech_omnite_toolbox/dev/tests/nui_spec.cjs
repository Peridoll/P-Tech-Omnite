const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
async function test(){
    const root=path.resolve(__dirname,'../../main/nui');
    const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'),{runScripts:'outside-only',url:'https://test-nui/'});
    const w=dom.window,d=w.document,calls=[];
    w.GetParentResourceName=()=> 'test-resource';
    w.fetch=async(url,options)=>{calls.push({action:new URL(url).pathname.slice(1),data:JSON.parse(options.body)});return {json:async()=>({ok:true})};};
    w.eval(fs.readFileSync(path.join(root,'app.js'),'utf8'));
    const state={action:'placementState',session:1,name:'seat_01',mlo:'hospital',kind:'chair',focused:true,saving:false,
        values:{right:0,forward:0,height:0,heading:90,style:1},styles:['標準','背筋を伸ばす','ゆったり']};
    const send=data=>w.dispatchEvent(new w.MessageEvent('message',{data}));
    const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
    const input=(id,value)=>{const el=d.getElementById(id);el.value=String(value);el.dispatchEvent(new w.Event('input'));};
    send(state);
    assert.equal(d.querySelectorAll('.numeric-input').length,5,'every slider has direct numeric input');
    const rightNumber=d.getElementById('number-right');
    rightNumber.focus(); rightNumber.value='0.37'; rightNumber.dispatchEvent(new w.Event('input'));
    assert.equal(d.getElementById('seat-right').value,'0.37','numeric input updates slider');
    rightNumber.value='99'; rightNumber.dispatchEvent(new w.Event('input'));
    assert.equal(d.getElementById('seat-right').value,'0.37','out-of-range draft does not move preview');
    rightNumber.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter'}));
    assert.equal(rightNumber.value,'2','Enter clamps to allowed range');
    rightNumber.focus(); rightNumber.value=''; rightNumber.dispatchEvent(new w.Event('input')); rightNumber.blur();
    assert.equal(rightNumber.value,'2','blank draft restores last valid value');
    send(state);
    assert(!d.getElementById('placement-panel').classList.contains('hidden'));
    input('seat-right',1.25);input('seat-height',0.4);input('seat-style',2);
    await pause(70);
    let updates=calls.filter(x=>x.action==='placementUpdate');
    assert.equal(updates.length,1,'rapid inputs coalesce into one update');
    assert.equal(updates[0].data.values.right,1.25);
    assert.equal(d.getElementById('value-style').textContent,'背筋を伸ばす');
    input('seat-forward',-0.25);input('seat-heading',270);
    d.getElementById('placement-save').click();
    await pause(20);
    const save=calls.find(x=>x.action==='placementSave');
    assert.equal(save.data.values.heading,270,'save includes input even before preview timer fires');
    assert.equal(save.data.values.forward,-0.25);
    assert(d.getElementById('placement-cancel').disabled,'cannot cancel a pending save');
    send({...state,values:save.data.values,saving:false,error:'保存失敗'});
    assert(!d.getElementById('placement-save').disabled);
    assert.equal(d.getElementById('seat-right').value,'1.25','failed save preserves sliders');
    assert.equal(d.getElementById('placement-error').textContent,'保存失敗');
    d.getElementById('placement-ground').click();
    await pause(20);
    assert.equal(calls.at(-1).action,'placementGround','ground button requests floor alignment');
    send({...state,values:{...save.data.values,height:-2.58},heightMin:-2.58,heightMax:2});
    assert.equal(d.getElementById('seat-height').min,'-2.58');
    assert.equal(d.getElementById('seat-height').value,'-2.58','floor alignment becomes slider minimum');
    assert.equal(d.getElementById('number-height').min,'-2.58','numeric lower bound tracks floor button');
    input('seat-right',1.5);
    const bedState={...state,session:2,kind:'bed',styles:['仰向け']};
    send(bedState);
    assert(!d.getElementById('style-row').classList.contains('hidden') && d.getElementById('seat-style').disabled,'bed shows its single supported posture');
    assert(d.getElementById('number-style').disabled,'single posture numeric selection is disabled too');
    input('seat-height',0.5);
    await pause(70);
    updates=calls.filter(x=>x.action==='placementUpdate');
    assert.equal(updates.at(-1).data.session,2,'new session remains responsive after clearing an old timer');
    d.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Alt'}));
    await pause(20);
    assert.equal(calls.at(-1).action,'placementFocus');
    send({...bedState,focused:false});
    assert(d.getElementById('placement-panel').classList.contains('viewing'));
    send({...bedState,focused:true});
    d.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
    await pause(20);
    assert.equal(calls.at(-1).action,'placementCancel');
    assert(d.getElementById('placement-panel').classList.contains('hidden'));
    send({action:'copyText',text:'Config.FixedSeats = {}'});
    assert.equal(d.getElementById('config-line').value,'Config.FixedSeats = {}','clipboard panel still works');
    dom.window.close();
    console.log('PASS: slider DOM events, throttling, final save values, retries, bed UI and cancellation');
}
test().catch(error=>{console.error(error);process.exitCode=1;});
